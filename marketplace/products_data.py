def get_all_products():
    return DIGITAL_PRODUCTS

def get_product_by_id(prod_id):
    for p in DIGITAL_PRODUCTS:
        if p['id'] == prod_id:
            return p
    return None

def get_related_products(current_id, limit=3):
    current = get_product_by_id(current_id)
    if not current:
        return DIGITAL_PRODUCTS[:limit]
    
    same_cat = [p for p in DIGITAL_PRODUCTS if p['category'] == current['category'] and p['id'] != current_id]
    others = [p for p in DIGITAL_PRODUCTS if p['category'] != current['category'] and p['id'] != current_id]
    
    results = same_cat + others
    return results[:limit]
